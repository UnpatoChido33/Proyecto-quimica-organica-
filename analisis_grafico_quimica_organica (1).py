        ("tolueno", "Tolueno"), ("toluene", "Tolueno"),
        ("diclorometano", "DCM"), ("dichloromethane", "DCM"), ("dcm", "DCM"),
        ("acetonitril", "Acetonitrilo"), ("itril", "Acetonitrilo"),
        ("dimetilformamida", "DMF"), ("dimethylformamide", "DMF"),
        ("benceno", "Benceno"), ("benzene", "Benceno"),
        ("dioxano", "1,4-Dioxano"),
