# Normalizar Medio
def norm_medio(x):
    t = sin_tildes(str(x)).lower()
    if "acid" in t: return "Ácido"
    if "basic" in t: return "Básico"
    if "neutr" in t: return "Neutro"
    if "apolar" in t or "no polar" in t: return "Apolar"
    return "No especificado"

df["Medio_n"] = df[COL["Medio"]].map(norm_medio)

# Normalizar Tipo de reacción (columna Tpr)
def norm_tipo(x):
    t = sin_tildes(str(x)).lower()
    if any(w in t for w in ("oxido-reduc", "redox")): return "Óxido-reducción"
    if "oxid" in t: return "Oxidación"
    if "reduc" in t and "alquil" not in t: return "Reducción"
    if "alquil" in t and "reduc" in t: return "Alquilación reductora"
    if "adic" in t and "nucleofil" in t: return "Adición nucleofílica"
    if "adic" in t and "conjug" in t: return "Adición conjugada"
    if "adic" in t: return "Otras adiciones"
    if "condens" in t: return "Condensación"
    if "acoplam" in t: return "Acoplamiento cruzado"
    if "sustit" in t: return "Sustitución"
    if "hidrol" in t: return "Hidrólisis"
    if any(w in t for w in ("descomp", "ruptura", "fragment", "termica")): return "Descomposición"
    if "olefin" in t or "wittig" in t: return "Olefinación"
    if "cicl" in t: return "Ciclación"
    return "Otras"

df["Tipo_n"] = df[COL["Tipo"]].map(norm_tipo)

