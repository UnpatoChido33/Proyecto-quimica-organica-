#2. Limpieza robusta
def sin_tildes(s):
    return "".join(c for c in unicodedata.normalize("NFD", str(s)) if unicodedata.category(c) != "Mn")

SUP = str.maketrans("⁰¹²³⁴⁵⁶⁷⁸⁹⁻", "0123456789-")

def a_num(x):
    """Convierte textos raros de SciFinder / Excel a float."""
    if pd.isna(x):
        return np.nan
    s = str(x).replace("\u200b", "").strip().translate(SUP)
    if s.lower() in ("rt", "ta", "r.t.", "room temp", "temperatura ambiente"):
        return 25.0
    s = re.sub(r"\s+", "", s)
    # notación científica tipo 1,20x10⁵ o 1.20e5
    m = re.match(r"^(-?[\d.,]+)[x×]10([+-]?\d+)$", s, flags=re.I)
    if m:
        return float(m.group(1).replace(",", ".")) * 10 ** int(m.group(2))
    m = re.match(r"^(-?[\d.,]+)[eE]([+-]?\d+)$", s)
    if m:
        return float(m.group(1).replace(",", ".")) * 10 ** int(m.group(2))
    try:
        return float(s.replace(",", "."))
    except ValueError:
        return np.nan

def reescala(v, lo, hi):
    if pd.isna(v):
        return v
    k = 0
    while v > hi and k < 5:
        v /= 10
        k += 1
    return v if lo <= v <= hi else np.nan

